"""Generate this client's OpenAPI 3.0 surface using Python 3's standard library.

The supported schema subset is deliberately limited to the supplied inriver spec.
Unsupported constructs and ambiguous operation names fail rather than silently
producing an incomplete client. Run with --check in CI to detect output drift.
"""
import argparse
