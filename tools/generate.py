import html
import json
from pathlib import Path
import re
from string import Template
import sys

ROOT = Path(__file__).resolve().parents[1]
LIB = ROOT / "src/InRiver.Rest.Lib"
TEMPLATES = Path(__file__).parent / "templates"
HEADER = "// <auto-generated>Generated by tools/generate.py from swagger.json. Do not edit.</auto-generated>\n"
VERBS = {"get", "post", "put", "delete", "patch", "head", "options"}
# These are C# naming overrides only; the source document is never rewritten.
NAMES = {
    ("get", "/api/v1.0.0/channels/snapshottags"): "GetChannelSnapshotTags",
    ("put", "/api/v1.0.0/extensionmanager:restartservice"): "RestartServicePut",
    ("get", "/api/v1.0.1/model/unusedfieldtypes"): "GetUnusedFieldTypes",
    ("delete", "/api/v1.0.0/model/restrictedfields:byfieldtype"): "DeleteRestrictedFieldPermissionByFieldType",
    ("get", "/api/v1.0.0/workareafolderquery/{id}"): "WorkareaFolderQueryById",
    ("get", "/api/v1.0.0/workareafolder/{workareaFolderId}/entityIds"): "GetWorkareaFolderEntityIds",
}
# Null means clear/unassign for these fields, rather than omit the update.
INCLUDE_NULL = {
    ("FieldValueModel", "value"),
    ("ChannelSnapshotTagModel", "snapshotTag"),
    ("SpecificationUpsertModel", "specificationValues"),
}
KEYWORDS = {"operator", "event", "namespace", "params", "object", "string", "default", "base", "ref", "out", "in"}


def cs_string(value):
    return json.dumps(value, ensure_ascii=True)


def identifier(value):
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", value):
        raise ValueError("Unsupported C# identifier: " + value)
    return "@" + value if value in KEYWORDS else value


def pascal(value):
    return identifier(value[0].upper() + value[1:])


def doc(text, indent="        "):
    lines = [indent + "/// <summary>"]
    for paragraph in str(text).splitlines():
        lines.append(indent + "/// <para>" + html.escape(paragraph, quote=False) + "</para>")
    return "\n".join(lines + [indent + "/// </summary>"])


def render(template_name, **values):
    return Template((TEMPLATES / template_name).read_text(encoding="utf-8")).substitute(**values)


def cstype(schema, optional=False):
    for unsupported in ("oneOf", "anyOf", "allOf", "not"):
        if unsupported in schema:
            raise ValueError("Unsupported schema construct: " + unsupported)
    if "$ref" in schema:
        result = identifier(schema["$ref"].split("/")[-1])
        return result + "?" if result == "LoadLevel" and (optional or schema.get("nullable")) else result
    kind = schema.get("type")
    if kind == "array":
        return "List<" + cstype(schema["items"]) + ">"
    if kind == "object":
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict) or extra is True:
            return "Dictionary<string, " + cstype(extra if isinstance(extra, dict) else {}) + ">"
        return "object"
    result = {None: "object", "string": "string", "integer": "int", "number": "double", "boolean": "bool"}.get(kind)
    if result is None:
        raise ValueError("Unsupported schema type: " + str(kind))
    if schema.get("format") == "int64":
        result = "long"
    elif schema.get("format") == "date-time":
        result = "DateTimeOffset"
    elif schema.get("format") == "uuid":
        result = "Guid"
    if result in ("int", "long", "double", "bool", "DateTimeOffset", "Guid") and (optional or schema.get("nullable")):
        result += "?"
    return result


def model(name, schema):
    if "enum" in schema:
        if schema["type"] != "integer":
            raise ValueError("Unsupported enum: " + name)
        members = ",\n".join("        [EnumMember] Value" + str(v) + " = " + str(v) for v in schema["enum"])
        return HEADER + "using System.Runtime.Serialization;\n\nnamespace InRiver.Rest.Lib.Model\n{\n" + doc(name, "    ") + "\n    [DataContract]\n    public enum " + name + "\n    {\n" + members + "\n    }\n}\n"
    if schema.get("type") != "object":
        raise ValueError("Unsupported model: " + name)
    required = schema.get("required", [])
    props = schema.get("properties", {})
    args, assignments, properties, tostring, equalities, hashes = [], [], [], [], [], []
    for wire, prop in props.items():
        member = pascal(wire)
        param = identifier(wire)
        typ = cstype(prop, optional=wire not in required)
        args.append(typ + " " + param + " = default(" + typ + ")")
        if wire in required and not prop.get("nullable") and prop.get("type") in ("string", "array", "object") and typ not in ("DateTimeOffset", "Guid"):
            assignments.append("            if(" + param + " == null) throw new ArgumentNullException(nameof(" + param + "));")
        assignments.append("            " + member + " = " + param + ";")
        include_null = wire in required or (name, wire) in INCLUDE_NULL
        attributes = "        [DataMember(Name=" + cs_string(wire) + ", EmitDefaultValue=" + str(include_null).lower() + ")]"
        if not include_null:
            attributes += "\n        [JsonProperty(NullValueHandling = NullValueHandling.Ignore)]"
        description = prop.get("description", "Gets or sets " + member + ".")
        if prop.get("deprecated"):
            description += " Deprecated by the upstream API."
        if "default" in prop:
            description += " Server default: " + json.dumps(prop["default"]) + "."
        properties.append(doc(description) + "\n" + attributes + "\n        public " + typ + " " + member + " { get; " + ("private " if prop.get("readOnly") else "") + "set; }")
        tostring.append('            sb.Append("  ' + member + ': ").Append(' + member + ').Append("\\n");')
        if typ.startswith("List<"):
            equalities.append("(" + member + " == input." + member + " || (" + member + " != null && input." + member + " != null && " + member + ".SequenceEqual(input." + member + ")))" )
            item_type = typ[5:-1]
            hashes.append("                if(" + member + " != null) foreach(var item in " + member + ") hash = hash * 59 + EqualityComparer<" + item_type + ">.Default.GetHashCode(item);")
        elif typ.startswith("Dictionary<"):
            equalities.append("(" + member + " == input." + member + " || (" + member + " != null && input." + member + " != null && " + member + ".OrderBy(p => p.Key, StringComparer.Ordinal).SequenceEqual(input." + member + ".OrderBy(p => p.Key, StringComparer.Ordinal))))")
            hashes.append("                if(" + member + " != null) foreach(var item in " + member + ".OrderBy(p => p.Key, StringComparer.Ordinal)) hash = hash * 59 + item.GetHashCode();")
        else:
            equalities.append("EqualityComparer<" + typ + ">.Default.Equals(" + member + ", input." + member + ")")
            hashes.append("                hash = hash * 59 + EqualityComparer<" + typ + ">.Default.GetHashCode(" + member + ");")
    # Preserve vendor extension properties on ProblemDetails.
    if schema.get("additionalProperties") is not False:
        properties.append('        [JsonExtensionData]\n        public IDictionary<string, JToken> AdditionalProperties { get; set; }')
        equalities.append("(AdditionalProperties == input.AdditionalProperties || (AdditionalProperties != null && input.AdditionalProperties != null && AdditionalProperties.OrderBy(p => p.Key, StringComparer.Ordinal).SequenceEqual(input.AdditionalProperties.OrderBy(p => p.Key, StringComparer.Ordinal))))")
        hashes.append("                if(AdditionalProperties != null) foreach(var item in AdditionalProperties.OrderBy(p => p.Key, StringComparer.Ordinal)) hash = hash * 59 + item.GetHashCode();")
    ctor_doc = doc("Initializes a new instance of " + name + ".") + "\n" + "\n".join(
        '        /// <param name="' + w + '">' + html.escape(p.get("description", w), quote=False).replace("\n", " ").replace("\r", "") + '</param>' for w, p in props.items())
    return HEADER + render("model.cs.template", name=name, description=doc(schema.get("description", name), "    "),
        constructor_doc=ctor_doc, args=", ".join(args), assignments="\n".join(assignments),
        properties="\n\n".join(properties), tostring="\n".join(tostring), equalities=" &&\n                ".join(equalities), hashes="\n".join(hashes))


def operation(tag, path, verb, op):
    name = NAMES.get((verb, path), re.sub(r"Async$", "", op["operationId"]))
    identifier(name)
    parameters = op.get("parameters", [])
    params = []
    for p in parameters:
        if p["in"] not in ("path", "query"):
            raise ValueError("Unsupported parameter location: " + p["in"])
        params.append((p["name"], cstype(p["schema"], optional=not p.get("required")), p.get("required", False), p.get("description", "")))
    body = op.get("requestBody")
    body_name = None
    if body:
        schema = body["content"]["application/json"]["schema"]
        body_name = schema.get("$ref", "body").split("/")[-1]
        body_name = body_name[0].lower() + body_name[1:]
        params.append((body_name, cstype(schema), body.get("required", False), body.get("description", "Request body.")))
    params.sort(key=lambda p: not p[2])
    args = ", ".join(t + " " + identifier(n) + ("" if req else " = default(" + t + ")") for n, t, req, _ in params)
    async_args = args + (", " if args else "") + "CancellationToken cancellationToken = default"
    call = ", ".join(identifier(p[0]) for p in params)
    async_call = call + (", " if call else "") + "cancellationToken"
    success = [r for status, r in op["responses"].items() if status.startswith("2")]
    if len(success) != 1:
        raise ValueError("Expected one success response: " + path)
    content = success[0].get("content")
    typ = cstype(content["application/json"]["schema"]) if content else "object"
    result = typ if content else "void"
    info_name = "EntityUploadMediaFromUrlWithHttpInfo" if tag == "Entity" and name == "UploadMediaFromUrl" else name + "WithHttpInfo"
    docs = doc(op.get("summary", name) + "\n" + op.get("description", ""))
    docs += '\n        /// <exception cref="ApiException">Thrown for an API error.</exception>'
    for n, _, req, description in params:
        docs += '\n        /// <param name="' + n + '">' + html.escape(description, quote=False).replace("\n", " ").replace("\r", "") + (" Required." if req else " Optional.") + '</param>'
    async_docs = docs + '\n        /// <param name="cancellationToken">Cancels the HTTP request and response buffering.</param>'
    setup = []
    for n, t, req, _ in params:
        if req and (t in ("string", "object") or t.startswith(("List<", "Dictionary<")) or t.endswith("Model")):
            setup.append('            if(' + identifier(n) + ' == null) throw new ApiException(400, "Missing required parameter: ' + n + '");')
    setup += ["            var localVarPath = " + cs_string(path) + ";", "            var localVarQueryParams = new List<KeyValuePair<string, string>>();"]
    for p in parameters:
        n = identifier(p["name"])
        if p["in"] == "path":
            setup.append('            localVarPath = localVarPath.Replace(' + cs_string("{" + p["name"] + "}") + ', Uri.EscapeDataString(HttpHelpers.ParameterToString(' + n + ', Configuration)));')
        else:
            fmt = "multi" if p["schema"].get("type") == "array" and p.get("explode", True) else "csv"
            if p.get("style", "form") != "form":
                raise ValueError("Unsupported query style: " + path)
            setup.append('            if(' + n + ' != null) localVarQueryParams.AddRange(HttpHelpers.ParameterToKeyValuePairs(' + cs_string(fmt) + ', ' + cs_string(p["name"]) + ', ' + n + ', Configuration));')
    setup.append("            object localVarPostBody = " + (identifier(body_name) if body_name else "null") + ";")
    task = "Task<" + typ + ">" if content else "Task"
    signatures = [(docs, result, name, args), (docs, "ApiResponse<" + typ + ">", info_name, args),
                  (async_docs, task, name + "Async", async_args), (async_docs, "Task<ApiResponse<" + typ + ">>", name + "AsyncWithHttpInfo", async_args)]
    declarations = "\n\n".join(d + "\n        " + t + " " + n + "(" + a + ");" for d, t, n, a in signatures)
    methods = render("operation.cs.template", docs=docs, async_docs=async_docs, name=name, result=result,
        info_name=info_name, args=args, call=call, async_args=async_args, async_call=async_call, typ=typ,
        setup="\n".join(setup), verb=verb.capitalize(), task=task,
        return_data="\n            return localVarResponse.Data;" if content else "")
    return name, declarations, methods


def generate(spec):
    if not spec.get("openapi", "").startswith("3.0."):
        raise ValueError("Expected OpenAPI 3.0")
    schemas = spec["components"]["schemas"]
    reachable = set()

    def visit(value):
        if isinstance(value, dict):
            if "$ref" in value:
                ref = value["$ref"]
                if not ref.startswith("#/components/schemas/"):
                    raise ValueError("Unsupported reference: " + ref)
                name = ref.split("/")[-1]
                if name not in reachable:
                    reachable.add(name)
                    visit(schemas[name])
            for v in value.values():
                visit(v)
        elif isinstance(value, list):
            for v in value:
                visit(v)

    visit(spec["paths"])
    output = {"Model/" + n + ".cs": model(n, schemas[n]) for n in sorted(reachable)}
    groups = collections.defaultdict(list)
    manifest = []
    for path, item in spec["paths"].items():
        for verb, op in item.items():
            if verb not in VERBS:
                raise ValueError("Unsupported path item: " + verb)
            tag = op["tags"][0]
            name, declarations, methods = operation(tag, path, verb, op)
            if any(n == name for n, _, _ in groups[tag]):
                raise ValueError("Duplicate operation name: " + tag + "." + name)
            groups[tag].append((name, declarations, methods))
            manifest.append({"tag": tag, "method": name, "verb": verb.upper(), "path": path})
    fields, properties, interfaces = [], [], []
    for tag, operations in sorted(groups.items()):
        output["Api/" + tag + "Api.cs"] = HEADER + render("api.cs.template", tag=tag, methods="\n\n".join(m for _, _, m in operations))
        output["Api/I" + tag + "Api.cs"] = HEADER + render("interface.cs.template", tag=tag, methods="\n\n".join(d for _, d, _ in operations))
        field = "_" + tag[0].lower() + tag[1:] + "Api"
        fields.append("        private I" + tag + "Api " + field + ";")
        properties.append(render("property.cs.template", tag=tag, field=field))
        interfaces.append("        I" + tag + "Api " + tag + "Api { get; }")
    output["Client/InRiverRestClient.Apis.cs"] = HEADER + "using System;\nusing InRiver.Rest.Lib.Api;\n\nnamespace InRiver.Rest.Lib.Client\n{\n    public sealed partial class InRiverRestClient\n    {\n" + "\n".join(fields) + "\n\n" + "\n".join(properties) + "    }\n}\n"
    output["Client/IinRiverClient.cs"] = HEADER + "using System;\nusing InRiver.Rest.Lib.Api;\n\nnamespace InRiver.Rest.Lib.Client\n{\n    public interface IinRiverClient : IDisposable\n    {\n" + "\n\n".join(interfaces) + "\n    }\n}\n"
    return output, manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = json.loads((ROOT / "swagger.json").read_text(encoding="utf-8"))
    output, manifest = generate(spec)
    output = {LIB / p: text for p, text in output.items()}
    output[ROOT / "tools/operations.json"] = json.dumps(manifest, indent=2) + "\n"
    # Only delete files previously produced by this generator, never unknown user files.
    stale = [p for folder in (LIB / "Api", LIB / "Model") for p in folder.glob("*.cs")
             if p not in output and p.read_text(encoding="utf-8").startswith(HEADER)]
    drift = stale + [p for p, text in output.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        if drift:
            print("Generated output is out of date:\n" + "\n".join(str(p.relative_to(ROOT)) for p in drift))
            return 1
    else:
        for p in stale:
            p.unlink()
        for p, text in output.items():
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8", newline="\n")
    print(str(len(manifest)) + " operations; generated output " + ("verified" if args.check else "updated"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
